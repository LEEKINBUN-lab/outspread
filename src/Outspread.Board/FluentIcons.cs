    /// <summary>官方 20_regular 那批图标画在 20×20 的设计网格上；形状本身通常只占 2…18。
    /// Viewbox 直接量 Path 时拿的是**几何包围盒** 16×16，于是按 1:1 塞进 16 的盒子，
    /// 右边和下边各切掉 2 个单位——他 10-26 报的"图标下方和右侧被截断"就是这一格。</summary>
    internal const double DesignSize = 20;

    /// <summary>一枚官方形状的图标；这段路径认不下来就返回 null，调用方退回文字而不是留一格空白。</summary>
    public static UIElement? Glyph(string data, double pixels, Color color)
    {
        if (Parse(data) is not { } geometry)
        {
            Diagnostics.Write($"fluent icon 认不下这段路径：{data[..Math.Min(48, data.Length)]}");
            return null;
        }

        var size = Math.Max(8, pixels);

        return new Viewbox
        {
            Width = size,
            Height = size,
            IsHitTestVisible = false,
            Child = new Microsoft.UI.Xaml.Shapes.Path
            {
                Data = geometry,
                Fill = new SolidColorBrush(color),

                // 显式按设计网格占位：Viewbox 缩的是 20×20 的整张纸，不是 16×16 的墨迹，
                // 右/下留白与官方 SVG 一致，不再被裁。
                Width = DesignSize,
                Height = DesignSize,
                Stretch = Stretch.None,
            },
        };
    }

    /// <summary>同一段官方路径，装成 <see cref="IconElement"/>：菜单项的 Icon 只收这一种。</summary>
    public static IconElement? Icon(string data, double pixels, Color color)
    {
        if (Parse(data) is not { } geometry)
        {
            Diagnostics.Write($"fluent icon 认不下这段路径：{data[..Math.Min(48, data.Length)]}");

            return null;
        }

        var size = Math.Max(8, pixels);

        return new PathIcon
        {
            Data = geometry,
            Width = size,
            Height = size,
            Foreground = new SolidColorBrush(color),
            IsHitTestVisible = false,
        };
    }

    /// <summary>
    /// 只吃大写 <c>M L H V C Z</c>——官方 20 Regular 那几枚全靠这六种。出现别的（弧线 <c>A</c>、小写相对命令、
    /// <c>S T Q</c>）就整段判 null：画半截形状比退回文字更糟，人会以为那是设计。
    /// </summary>
    private static PathGeometry? Parse(string data)
    {
        var tokens = Tokenize(data);

        if (tokens is null)
        {
            return null;
        }

        var geometry = new PathGeometry();
        PathFigure? figure = null;
        double x = 0;
        double y = 0;
        var at = 0;

        while (at < tokens.Count)
        {
            if (tokens[at].Length != 1 || !"MLHVZC".Contains(tokens[at]))
            {
                return null;
            }

            var command = tokens[at];
            at++;

            switch (command)
            {
                case "M":
                {
                    if (!TryPair(tokens, ref at, ref x, ref y))
                    {
                        return null;
                    }

                    figure = new PathFigure { StartPoint = new Point(x, y) };
                    geometry.Figures.Add(figure);

                    // SVG 里 M 后面再跟的每一对坐标是隐式直线段，不是新起点。
                    while (at < tokens.Count && IsNumber(tokens[at]))
                    {
                        if (!TryPair(tokens, ref at, ref x, ref y))
                        {
                            return null;
                        }

                        figure.Segments.Add(new LineSegment { Point = new Point(x, y) });
                    }

                    break;
                }

                case "L":
                {
                    do
                    {
                        if (figure is null || !TryPair(tokens, ref at, ref x, ref y))
                        {
                            return null;
                        }

                        figure.Segments.Add(new LineSegment { Point = new Point(x, y) });
                    }
                    while (at < tokens.Count && IsNumber(tokens[at]));

                    break;
                }

                case "H":
                {
                    do
                    {
                        if (figure is null || !TryNumber(tokens, ref at, ref x))
                        {
                            return null;
                        }

                        figure.Segments.Add(new LineSegment { Point = new Point(x, y) });
                    }
                    while (at < tokens.Count && IsNumber(tokens[at]));

                    break;
                }

                case "V":
                {
                    do
                    {
                        if (figure is null || !TryNumber(tokens, ref at, ref y))
                        {
                            return null;
                        }

                        figure.Segments.Add(new LineSegment { Point = new Point(x, y) });
                    }
                    while (at < tokens.Count && IsNumber(tokens[at]));

                    break;
                }

                case "C":
                {
                    do
                    {
                        if (figure is null || !TryTriple(tokens, ref at, out var c1x, out var c1y, out var c2x, out var c2y, ref x, ref y))
                        {
                            return null;
                        }

                        figure.Segments.Add(new BezierSegment
                        {
                            Point1 = new Point(c1x, c1y),
                            Point2 = new Point(c2x, c2y),
                            Point3 = new Point(x, y),
                        });
                    }
                    while (at < tokens.Count && IsNumber(tokens[at]));

                    break;
                }

                default:
                {
                    if (figure is null)
                    {
                        return null;
                    }

                    figure.IsClosed = true;
                    figure = null;
                    break;
                }
            }
        }

        return geometry.Figures.Count > 0 ? geometry : null;
    }

    private static bool IsNumber(string token) => token.Length > 1 || (token[0] >= '0' && token[0] <= '9');

    private static bool TryNumber(List<string> tokens, ref int at, ref double to)
    {
        if (at >= tokens.Count || !double.TryParse(tokens[at], NumberStyles.Float, CultureInfo.InvariantCulture, out to))
        {
            return false;
        }

        at++;

        return true;
    }

    private static bool TryPair(List<string> tokens, ref int at, ref double x, ref double y) => TryNumber(tokens, ref at, ref x) && TryNumber(tokens, ref at, ref y);

    private static bool TryTriple(List<string> tokens, ref int at, out double c1x, out double c1y, out double c2x, out double c2y, ref double x, ref double y)
    {
        c1x = c1y = c2x = c2y = 0;

        if (!TryNumber(tokens, ref at, ref c1x) || !TryNumber(tokens, ref at, ref c1y)
            || !TryNumber(tokens, ref at, ref c2x) || !TryNumber(tokens, ref at, ref c2y))
        {
            return false;
        }

        return TryNumber(tokens, ref at, ref x) && TryNumber(tokens, ref at, ref y);
    }

    private static readonly Regex Scanner = new("[A-Za-z]|[-+]?[0-9]*\\.?[0-9]+([eE][-+]?[0-9]+)?", RegexOptions.CultureInvariant);

    /// <summary>切成"单字母命令 + 数字"两种记号。凡是切不进这两种的字符都算没吃掉——整段判 null，
    /// 因为漏读一个命令正是把图标画歪的那种错，宁可退回文字。</summary>
    private static List<string>? Tokenize(string data)
    {
        var tokens = new List<string>();
        var consumed = 0;

        foreach (Match match in Scanner.Matches(data))
        {
            tokens.Add(match.Value);
            consumed += match.Value.Length;
        }

        // 逗号在 SVG 里是合法分隔符，所以先摊成空格再数；剩下的每个非空白字符都必须被某个记号吃掉。
        var meaningful = data.Replace(',', ' ').Count(c => !char.IsWhiteSpace(c));

        return meaningful == consumed ? tokens : null;
    }
